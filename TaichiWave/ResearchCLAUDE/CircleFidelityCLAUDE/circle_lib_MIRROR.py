"""Circle fidelity on the REAL solver: angular-mode energy and the m = 0 error vs a Bessel reference.

Generated by Claude Opus 5.5 -- 01/10/2026.

A centred pulse in a pinned circle is, in the continuum, purely radial (angular mode m = 0).
So every bit of energy found in modes m != 0 is lattice error (anisotropy + staircase wall).

Method per sample time:
  * u_mid = (u^n + u^(n-1))/2 and v = (u^n - u^(n-1))/dt from the solver's two time levels;
  * both are fitted with QUINTIC B-splines (scipy prefilter on the host), evaluated on the GPU
    (Taichi kernel below) on a polar grid about the centre: rings r = (k+1/2) dr, dr = 0.5,
    r <= R - 2, n_theta = next power of two >= 2 pi r (arc spacing <= 1 cell);
  * the spline's analytic derivative gives grad u -> (u_r, u_theta / r);
  * rFFT in angle. Mode m of u maps to mode m of u_r and of u_theta/r, so the energy splits by m:
        E_m = 1/2 * sum_rings 2 pi r dr * w_m * (|V_m|^2 + |Ur_m|^2 + |Ut_m|^2)
    (w_m = 1 for m = 0 / Nyquist, 2 otherwise: the rFFT half-spectrum).
  * eps_ang = sum_{m != 0} E_m / sum_m E_m  (energy fraction off the radial mode);
    eps_u   = the same with |U_m|^2 (sum of u^2 instead of energy).
  * eps_0   = energy of (m = 0 part - u_ref) / exact total energy (pi/2), u_ref the exact
    Fourier-Bessel series of the same Gaussian in the circle of radius R (nominal, the mask's R);
    eps_u0  = || U_0 - u_ref ||^2 / || u(0) ||^2 (sum of u^2, normalised by the INITIAL pulse:
    u itself is not conserved, at the 2D refocus most energy is kinetic).

Time base: the app starts at rest with u^(-1) = u^0, so the discrete solution is even about
n = -1/2: level n sits at t = (n + 1/2) dt, and u_mid of levels (n-1, n) at t = n dt. The
reference is averaged the same way (u_ref(t +- dt/2)). dt = Co (c = 1, lattice spacing 1).
"""
import math
import os
import sys

import numpy as np
from scipy import ndimage as nd
from scipy import special as sp
import taichi as ti

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
