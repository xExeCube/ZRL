import membrane_core_MIRROR as mc          # noqa: E402

S3H = math.sqrt(3) / 2
DR = 0.5
M_STORE = 64                               # per-m energies kept for m = 0 .. M_STORE


# ---------------------------------------------------------------- quintic B-spline on the GPU
@ti.func
def _b5(x):
    t = ti.abs(x)
    r = 0.0
    if t < 1.0:
        r = (66.0 - 60.0 * t * t + 30.0 * t ** 4 - 10.0 * t ** 5) / 120.0
    elif t < 2.0:
        r = (51.0 + 75.0 * t - 210.0 * t * t + 150.0 * t ** 3 - 45.0 * t ** 4 + 5.0 * t ** 5) / 120.0
    elif t < 3.0:
        r = (3.0 - t) ** 5 / 120.0
    return r


@ti.func
def _db5(x):                               # d b5 / dx
    t = ti.abs(x)
    d = 0.0
    if t < 1.0:
        d = (-120.0 * t + 120.0 * t ** 3 - 50.0 * t ** 4) / 120.0
    elif t < 2.0:
        d = (75.0 - 420.0 * t + 450.0 * t * t - 180.0 * t ** 3 + 25.0 * t ** 4) / 120.0
    elif t < 3.0:
        d = -5.0 * (3.0 - t) ** 4 / 120.0
    return d if x >= 0 else -d


@ti.kernel
def k_eval(CU: ti.types.ndarray(ndim=2), CV: ti.types.ndarray(ndim=2), P: ti.types.ndarray(ndim=2),
           OUT: ti.types.ndarray(ndim=2), N: ti.i32):
    """P[p] = (fi, fj) index coordinates; OUT[p] = (u, v, du/di, du/dj)."""
    for p in range(P.shape[0]):
        fi, fj = P[p, 0], P[p, 1]
        i0 = ti.cast(ti.floor(fi), ti.i32) - 2
        j0 = ti.cast(ti.floor(fj), ti.i32) - 2
        u = 0.0
        v = 0.0
        ui = 0.0
        uj = 0.0
        for a in range(6):
            ii = i0 + a
            if 0 <= ii < N:
                wi = _b5(fi - ii)
                dwi = _db5(fi - ii)
                for b in range(6):
                    jj = j0 + b
                    if 0 <= jj < N:
                        wj = _b5(fj - jj)
                        cu = CU[ii, jj]
                        u += wi * wj * cu
                        v += wi * wj * CV[ii, jj]
                        ui += dwi * wj * cu
                        uj += wi * _db5(fj - jj) * cu
        OUT[p, 0] = u
        OUT[p, 1] = v
        OUT[p, 2] = ui
        OUT[p, 3] = uj


# ---------------------------------------------------------------- the membrane
def make_membrane(lattice, N, co_rel, sigma, R_target=None):
    """lattice: 'sq5' | 'sq9' | 'tri'. co_rel: Co as a number (>= 0.01) or ('rel', f) = f * C_max.
    R_target: force this circle radius (square: via p.rad); default the tri radius at this N,
    so all three lattices get the SAME radius in lattice spacings."""
    c = (N - 1) / 2
    R_tri = c * S3H - 1.5
    R = R_tri if R_target is None else R_target
    p = mc.Params()
    p.N, p.shape, p.bc, p.src, p.sigma, p.damp = N, 'circle', 'dirichlet', 'pulse', float(sigma), 0.0
    p.sx = p.sy = 0.0
    if lattice == 'tri':
        p.lattice, p.stencil, p.rad = 'tri', 5, R / R_tri
    else:
        p.lattice, p.stencil, p.rad = 'sq', (9 if lattice == 'sq9' else 5), R / (c - 1.5)
    p.Co = 0.5
    m = mc.Membrane(p)
    m.record = False
    cmax = m.co_limit()
    co = cmax * co_rel[1] if isinstance(co_rel, tuple) else float(co_rel)
    if abs(co - p.Co) > 0:
        m.p.Co = co
        m.reseed()
    assert abs(m.dom_R() - R) < 1e-9, (m.dom_R(), R)
    cx, cy = m.cell_xy(*m.src[:2])
    assert abs(cx) < 1e-9 and abs(cy) < 1e-9, m.src
    return m, R, co, cmax


# ---------------------------------------------------------------- polar grid
class Polar:
    def __init__(self, m, R):
        self.R = R
        rmax = R - 2.0
        K = int(rmax / DR)
        r = (np.arange(K) + 0.5) * DR
        nth = np.maximum(64, 2 ** np.ceil(np.log2(2 * np.pi * r)).astype(int))
        self.bands = []                    # (r array, n_theta, offset into the flat point list)
        pts = []
        off = 0
        c = m.c()
        tri = m.tri()
        for n in np.unique(nth):
            rb = r[nth == n]
            th = 2 * np.pi * np.arange(n) / n
            X = rb[:, None] * np.cos(th)[None, :]
            Y = rb[:, None] * np.sin(th)[None, :]
            if tri:
                db = Y / S3H
                fi, fj = c + X - 0.5 * db, c + db
            else:
                fi, fj = c + X, c + Y
            pts.append(np.stack([fi.ravel(), fj.ravel()], 1))
            self.bands.append((rb, int(n), off, np.cos(th), np.sin(th)))
            off += rb.size * n
        self.r = r
        self.P = ti.ndarray(dtype=ti.f64, shape=(off, 2))
        self.P.from_numpy(np.concatenate(pts))
        self.OUT = ti.ndarray(dtype=ti.f64, shape=(off, 4))
        self.npts = off
        self.mmax = int(nth.max()) // 2
        self.N = m.N
        self.tri = tri
        self.CU = ti.ndarray(dtype=ti.f64, shape=(m.N, m.N))
        self.CV = ti.ndarray(dtype=ti.f64, shape=(m.N, m.N))

    def analyse(self, u_mid, v):
        """-> dict: E_m (m <= mmax), Q_m (sum u^2 per m), U0(r) (the radial profile)."""
        self.CU.from_numpy(nd.spline_filter(u_mid, order=5, mode='mirror'))
        self.CV.from_numpy(nd.spline_filter(v, order=5, mode='mirror'))
        k_eval(self.CU, self.CV, self.P, self.OUT, self.N)
        O = self.OUT.to_numpy()
        E = np.zeros(self.mmax + 1)
        Q = np.zeros(self.mmax + 1)
        U0, V0, R0 = [], [], []
        for rb, n, off, co, si in self.bands:
            blk = O[off:off + rb.size * n].reshape(rb.size, n, 4)
            u, vv, ui, uj = blk[..., 0], blk[..., 1], blk[..., 2], blk[..., 3]
            if self.tri:
                ux, uy = ui, (uj - 0.5 * ui) / S3H
            else:
                ux, uy = ui, uj
            ur = ux * co[None, :] + uy * si[None, :]
            ut = -ux * si[None, :] + uy * co[None, :]          # (1/r) du/dtheta
            Fu = np.fft.rfft(u, axis=1) / n
            Fv = np.fft.rfft(vv, axis=1) / n
            Fr = np.fft.rfft(ur, axis=1) / n
            Ft = np.fft.rfft(ut, axis=1) / n
            w = np.full(n // 2 + 1, 2.0)
            w[0] = 1.0
            w[-1] = 1.0
            ring = 2 * np.pi * rb[:, None] * DR * w[None, :]
            E[:n // 2 + 1] += 0.5 * (ring * (np.abs(Fv) ** 2 + np.abs(Fr) ** 2 + np.abs(Ft) ** 2)).sum(0)
            Q[:n // 2 + 1] += (ring * np.abs(Fu) ** 2).sum(0)
            U0.append(Fu[:, 0].real)
            V0.append(Fv[:, 0].real)
            R0.append(Fr[:, 0].real)
        return E, Q, np.concatenate(U0), np.concatenate(V0), np.concatenate(R0)


# ---------------------------------------------------------------- continuum reference
class BesselRef:
    """u(r,t) = sum_k a_k J0(j_k r/R) cos(j_k t/R) for a Gaussian of width sigma at rest at t = 0."""
    def __init__(self, R, sigma, r):
        K = int(8.6 * R / (np.pi * sigma)) + 20
        j = sp.jn_zeros(0, K)
        a = 2 * sigma ** 2 / (R ** 2 * sp.j1(j) ** 2) * np.exp(-0.5 * (j * sigma / R) ** 2)
        keep = np.abs(a) > 1e-18 * np.abs(a).max()
        self.j, self.a, self.R = j[keep], a[keep], R
        self.J = sp.j0(np.outer(r, self.j / R))        # [rings, modes]
        self.J1 = -sp.j1(np.outer(r, self.j / R)) * (self.j / R)[None, :]   # d/dr J0(j r/R)
        self.r = r

    def at(self, t):
        return self.J @ (self.a * np.cos(self.j * t / self.R))

    def dr_at(self, t):
        return self.J1 @ (self.a * np.cos(self.j * t / self.R))


# ---------------------------------------------------------------- a run
def run(lattice, N, co_rel, sigma_spec, trips=10, per_trip=4, verbose=False, R=None):
    """sigma_spec: number (cells) or ('frac', f) = f * R. R: circle radius (default: the tri radius
    at this N, used for all three lattices; must not exceed it)."""
    c = (N - 1) / 2
    R = c * S3H - 1.5 if R is None else R
    sigma = R * sigma_spec[1] if isinstance(sigma_spec, tuple) else float(sigma_spec)
    m, R, co, cmax = make_membrane(lattice, N, co_rel, sigma, R)
    pol = Polar(m, R)
    ref = BesselRef(R, sigma, pol.r)
    dt = co
    T = 2 * R                                           # one round trip (c = 1)
    w = 2 * np.pi * pol.r * DR
    out = dict(lattice=lattice, N=N, R=R, sigma=sigma, Co=co, Cmax=cmax, co_rel=co / cmax,
               nodes=int(m.mask_np.sum()), npolar=pol.npts, times=[], trip=[], eps_ang=[], eps_u=[],
               eps_0=[], eps_u0=[], E_tot=[], Em=[], cls=[])
    # sample 0: the seeded Gaussian (exact data on the nodes) -> the interpolation floor
    targets = [0] + [int(round(k * T / per_trip / dt)) for k in range(1, trips * per_trip + 1)]
    n_done = 0
    for n in targets:
        if n > n_done:
            m.step(n - n_done)
            n_done = n
        u1 = m.level(1).astype(np.float64)
        u0 = m.level(0).astype(np.float64)
        um, v = 0.5 * (u1 + u0), (u1 - u0) / dt
        E, Q, U0, V0, R0 = pol.analyse(um, v)
        t = n * dt
        rp, rq = ref.at(t + dt / 2), ref.at(t - dt / 2)
        vref = (rp - rq) / dt
        rref = 0.5 * (ref.dr_at(t + dt / 2) + ref.dr_at(t - dt / 2))
        # m = 0 error in the ENERGY norm, over the exact total energy pi/2 (any sigma)
        e0 = float(0.5 * (w * ((V0 - vref) ** 2 + (R0 - rref) ** 2)).sum() / (np.pi / 2))
        eu0 = float((w * (U0 - 0.5 * (rp + rq)) ** 2).sum() / (w * np.exp(-pol.r ** 2 / sigma ** 2)).sum())
        mm = np.arange(E.size)
        nz = mm > 0
        cls = [E[nz & (mm % 12 == 0)].sum(), E[nz & (mm % 4 == 0) & (mm % 12 != 0)].sum(),
               E[nz & (mm % 6 == 0) & (mm % 12 != 0)].sum(),
               E[nz & (mm % 4 != 0) & (mm % 6 != 0)].sum()]
        out['times'].append(t)
        out['trip'].append(t / T)
        out['eps_ang'].append(float(E[1:].sum() / E.sum()) if E.sum() > 0 else 0.0)
        out['eps_u'].append(float(Q[1:].sum() / Q.sum()))
        out['eps_0'].append(e0)
        out['eps_u0'].append(eu0)
        out['E_tot'].append(float(E.sum()))
        out['Em'].append(E[:M_STORE + 1].tolist())
        out['cls'].append([float(x) / float(E.sum()) for x in cls])   # m%12, m%4 only, m%6 only, other
        if verbose:
            print(f'  t/T={t / T:6.3f}  eps_ang={out["eps_ang"][-1]:.3e}  eps_u={out["eps_u"][-1]:.3e}  '
                  f'eps_0={e0:.3e}  E={E.sum():.6g}', flush=True)
    return out
