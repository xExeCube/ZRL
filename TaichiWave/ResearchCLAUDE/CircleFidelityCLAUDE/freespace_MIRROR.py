"""Free-space control: the same centred pulse travels one round-trip DISTANCE (2R) in a circle so
large that it never reaches the wall. Its m != 0 energy is the lattice's own anisotropy (no
staircase). Compare with the sweep's trip-1 value at the small R.
Generated by Claude Opus 5.5 -- 01/10/2026. -> OutCLAUDE/freespace_MIRROR.json"""
import json, os
import numpy as np
import circle_lib_MIRROR as cl
cl.mc.init_taichi('cuda', quiet=True)
out = []
for Nsmall, Nbig in [(513, 1153), (1025, 2305)]:
    Rs = (Nsmall - 1) / 2 * cl.S3H - 1.5
    for sg in [3.0, Rs / 40]:
        for lat in ['sq5', 'sq9', 'tri']:
            m, R, co, _ = cl.make_membrane(lat, Nbig, 0.5, sg)
            pol = cl.Polar(m, R)
            n = int(round(2 * Rs / co))
            m.step(n)
            u1, u0 = m.level(1), m.level(0)
            E, Q, *_ = pol.analyse(0.5 * (u1 + u0), (u1 - u0) / co)
            e = float(E[1:].sum() / E.sum())
            out.append(dict(lattice=lat, N_small=Nsmall, R_small=Rs, sigma=sg, R_big=R, dist=n * co, eps_free=e,
                            E_in_view=float(E.sum())))
            print(f'{lat} Nsmall={Nsmall} sig={sg:.2f} dist={n * co:.0f} R_big={R:.0f}: eps_free={e:.2e} E={E.sum():.4f}', flush=True)
json.dump(out, open(os.path.join(cl.HERE, 'OutCLAUDE', 'freespace_MIRROR.json'), 'w'))
