"""The sweep: lattices x N x Co x pulse width, 10 round trips, on the real solver (CUDA f64).

Generated by Claude Opus 5.5 -- 01/10/2026. Results append to OutCLAUDE/sweep_MIRROR.json
(one record per run; finished runs are skipped on a re-run).
    python sweep_MIRROR.py [--N 257 513 1025 2049] [--trips 10]
"""
import argparse
import json
import os
import time

import circle_lib_MIRROR as cl

ap = argparse.ArgumentParser()
ap.add_argument('--N', type=int, nargs='+', default=[257, 513, 1025, 2049])
ap.add_argument('--co', nargs='+', default=['0.5', 'r0.9', 'r0.99'])
ap.add_argument('--sig', nargs='+', default=['3', 'f0.025'])
ap.add_argument('--lat', nargs='+', default=['sq5', 'sq9', 'tri'])
ap.add_argument('--trips', type=int, default=10)
ap.add_argument('--out', default=os.path.join(cl.HERE, 'OutCLAUDE', 'sweep_MIRROR.json'))
a = ap.parse_args()
cl.mc.init_taichi('cuda', quiet=True)

res = json.load(open(a.out)) if os.path.exists(a.out) else []
key = lambda r: (r['lattice'], r['N'], r['co_tag'], r['sig_tag'])
done = {key(r) for r in res}
for N in a.N:
    for sg in a.sig:
        for co in a.co:
            for lat in a.lat:
                if (lat, N, co, sg) in done:
                    continue
                t0 = time.time()
                co_rel = ('rel', float(co[1:])) if co.startswith('r') else float(co)
                sig = ('frac', float(sg[1:])) if sg.startswith('f') else float(sg)
                r = cl.run(lat, N, co_rel, sig, trips=a.trips)
                r['co_tag'], r['sig_tag'], r['secs'] = co, sg, time.time() - t0
                res.append(r)
                json.dump(res, open(a.out, 'w'), default=float)
                e = r['eps_ang']
                print(f'{lat:4s} N={N:5d} Co={r["Co"]:.4f} sig={r["sigma"]:6.2f}  eps_ang trip1={e[4]:.2e} '
                      f'trip10={e[-1]:.2e}  eps_0 trip1={r["eps_0"][4]:.2e}  {r["secs"]:.0f}s', flush=True)
